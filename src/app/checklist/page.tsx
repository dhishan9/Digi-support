"use client";

import { useState, useMemo, useRef } from "react";
import servicesData from "@/data/services.json";

/* ── Types ── */
interface Service {
  id: string;
  name: string;
  documents: string[];
  fee: string;
  time: string;
}

const services: Service[] = servicesData;

/* Quick filter pills for common searches */
const POPULAR_SEARCHES = [
  "Senior",
  "Pension",
  "Health",
  "Aadhaar",
  "Certificate",
  "Card",
];

export default function ChecklistPage() {
  const [query, setQuery] = useState("");
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [checked, setChecked] = useState<Record<string, boolean>>({});
  const detailRef = useRef<HTMLDivElement | null>(null);

  /* Filter services by search query in name or documents */
  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return services;
    return services.filter(
      (s) =>
        s.name.toLowerCase().includes(q) ||
        s.documents.some((d) => d.toLowerCase().includes(q))
    );
  }, [query]);

  /* Currently selected service */
  const selected = services.find((s) => s.id === selectedId) ?? null;

  /* Toggle a document checkbox */
  const toggle = (doc: string) =>
    setChecked((prev) => ({ ...prev, [doc]: !prev[doc] }));

  /* Select all or deselect all for current service */
  const toggleAll = (selectState: boolean) => {
    if (!selected) return;
    const next: Record<string, boolean> = {};
    selected.documents.forEach((doc) => {
      next[doc] = selectState;
    });
    setChecked(next);
  };

  /* Select a service, reset checkboxes, and scroll to details */
  const selectService = (id: string) => {
    setSelectedId(id);
    setChecked({});
    setTimeout(() => {
      detailRef.current?.scrollIntoView({ behavior: "smooth", block: "start" });
    }, 50);
  };

  /* ── PDF download ── */
  const downloadPdf = async () => {
    if (!selected) return;

    const { jsPDF } = await import("jspdf");
    const doc = new jsPDF();

    const pageWidth = doc.internal.pageSize.getWidth();

    // Title
    doc.setFontSize(20);
    doc.setFont("helvetica", "bold");
    doc.text("Digi-Support — Document Checklist", pageWidth / 2, 20, {
      align: "center",
    });

    // Service name
    doc.setFontSize(16);
    doc.text(selected.name, pageWidth / 2, 35, { align: "center" });

    // Divider line
    doc.setDrawColor(180);
    doc.line(15, 40, pageWidth - 15, 40);

    // Fee & Time
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    doc.text(`Fee: ${selected.fee}`, 15, 50);
    doc.text(`Estimated Time: ${selected.time}`, 15, 58);

    // Documents header
    doc.setFontSize(14);
    doc.setFont("helvetica", "bold");
    doc.text("Required Documents:", 15, 72);

    // Document list with check status
    doc.setFontSize(12);
    doc.setFont("helvetica", "normal");
    let y = 82;
    selected.documents.forEach((docName) => {
      const isChecked = checked[docName] ?? false;
      const mark = isChecked ? "[x]" : "[ ]";
      const status = isChecked ? " — Ready" : " — Not Ready";
      doc.text(`${mark}  ${docName}${status}`, 20, y);
      y += 10;
      if (y > 270) {
        doc.addPage();
        y = 20;
      }
    });

    // Summary
    const total = selected.documents.length;
    const ready = selected.documents.filter((d) => checked[d]).length;
    y += 8;
    doc.setFont("helvetica", "bold");
    doc.text(`Summary: ${ready} of ${total} documents ready`, 15, y);

    // Footer
    doc.setFontSize(9);
    doc.setFont("helvetica", "italic");
    doc.text(
      `Generated by Digi-Support on ${new Date().toLocaleDateString("en-IN")}`,
      pageWidth / 2,
      285,
      { align: "center" }
    );

    doc.save(`${selected.id}_checklist.pdf`);
  };

  return (
    <div className="space-y-8">
      {/* Header */}
      <div className="text-center">
        <h1 className="text-3xl font-extrabold sm:text-4xl">
          📋 Registration Checklists
        </h1>
        <p className="mt-2 text-lg text-gray-500">
          Find any government service below to see exact documents, fees, and processing times.
        </p>
      </div>

      {/* Search & Quick Filters */}
      <div className="mx-auto max-w-2xl space-y-3">
        <div className="relative">
          <label htmlFor="search" className="sr-only">
            Search services or documents
          </label>
          <input
            id="search"
            type="text"
            placeholder="🔍  Search services or documents (e.g. Senior, Ration, Pension)…"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            className="w-full rounded-2xl border-2 border-[var(--border)] bg-[var(--surface)] px-5 py-3.5 text-lg shadow-sm transition-colors focus:border-[var(--primary)] focus:outline-none"
          />
          {query && (
            <button
              onClick={() => setQuery("")}
              className="absolute right-4 top-3.5 text-gray-400 hover:text-gray-700 text-lg font-bold"
              aria-label="Clear search"
            >
              ✕
            </button>
          )}
        </div>

        {/* Quick search tags */}
        <div className="flex flex-wrap items-center gap-2 pt-1 text-sm">
          <span className="font-semibold text-gray-500">Quick Filters:</span>
          {POPULAR_SEARCHES.map((tag) => (
            <button
              key={tag}
              onClick={() => setQuery(query === tag ? "" : tag)}
              className={`rounded-full px-3 py-1 font-semibold transition-colors cursor-pointer border ${
                query.toLowerCase() === tag.toLowerCase()
                  ? "bg-[var(--primary)] text-white border-[var(--primary)]"
                  : "bg-[var(--surface)] border-[var(--border)] text-[var(--fg)] hover:bg-gray-200"
              }`}
            >
              {tag}
            </button>
          ))}
          {query && (
            <button
              onClick={() => setQuery("")}
              className="text-xs text-red-600 hover:underline font-bold ml-1"
            >
              Clear filter
            </button>
          )}
        </div>

        {/* Count indicator */}
        <p className="text-sm text-gray-500">
          Showing {filtered.length} of {services.length} government services
        </p>
      </div>

      {/* Service cards grid */}
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
        {filtered.map((s) => (
          <button
            key={s.id}
            onClick={() => selectService(s.id)}
            className={`card-interactive rounded-2xl border-2 p-5 text-left shadow-sm cursor-pointer ${
              selectedId === s.id
                ? "border-[var(--primary)] bg-blue-50 ring-2 ring-[var(--primary)]"
                : "border-[var(--border)] bg-[var(--surface)] hover:border-blue-400"
            }`}
          >
            <h3 className="text-xl font-bold">{s.name}</h3>
            <p className="mt-1 text-sm text-gray-500">
              Fee: {s.fee} &nbsp;·&nbsp; Time: {s.time}
            </p>
            <p className="mt-2 text-sm text-gray-400">
              📁 {s.documents.length} documents required
            </p>
          </button>
        ))}
        {filtered.length === 0 && (
          <div className="col-span-full py-12 text-center text-lg text-gray-500">
            No services match &quot;{query}&quot;. Try searching for &quot;Aadhaar&quot;, &quot;Pension&quot;, or &quot;Card&quot;.
          </div>
        )}
      </div>

      {/* ── Selected service detail panel ── */}
      {selected && (
        <section
          ref={detailRef}
          className="scroll-mt-24 rounded-3xl border-2 border-[var(--primary)] bg-[var(--surface)] p-6 sm:p-8 shadow-lg animate-slide-down"
        >
          <div className="flex flex-wrap items-center justify-between gap-4">
            <h2 className="text-2xl font-extrabold text-[var(--primary)]">
              {selected.name}
            </h2>
            <div className="flex gap-2">
              <button
                onClick={() => toggleAll(true)}
                className="rounded-lg border-2 border-[var(--border)] bg-white px-3 py-1.5 text-sm font-semibold hover:bg-gray-100 cursor-pointer"
              >
                Select All
              </button>
              <button
                onClick={() => toggleAll(false)}
                className="rounded-lg border-2 border-[var(--border)] bg-white px-3 py-1.5 text-sm font-semibold hover:bg-gray-100 cursor-pointer"
              >
                Deselect All
              </button>
            </div>
          </div>

          <div className="mt-3 flex flex-wrap gap-3 text-base">
            <span className="rounded-lg bg-green-100 px-3 py-1 font-semibold text-green-800">
              💰 Fee: {selected.fee}
            </span>
            <span className="rounded-lg bg-blue-100 px-3 py-1 font-semibold text-blue-800">
              ⏱ Time: {selected.time}
            </span>
          </div>

          {/* Document checklist */}
          <h3 className="mt-6 text-xl font-bold">
            Required Documents — Tap to check off what you have:
          </h3>
          <ul className="mt-3 space-y-3">
            {selected.documents.map((doc) => (
              <li key={doc}>
                <label
                  className={`flex cursor-pointer items-center gap-3 rounded-2xl border-2 px-4 py-3.5 transition-all ${
                    checked[doc]
                      ? "border-green-400 bg-green-50/70 shadow-xs"
                      : "border-[var(--border)] bg-white hover:bg-gray-50"
                  }`}
                >
                  <input
                    type="checkbox"
                    checked={checked[doc] ?? false}
                    onChange={() => toggle(doc)}
                    className="h-6 w-6 shrink-0 accent-[var(--primary)] cursor-pointer"
                  />
                  <span
                    className={`text-lg select-none transition-all ${
                      checked[doc] ? "text-green-800 line-through font-medium" : "text-gray-900"
                    }`}
                  >
                    {doc}
                  </span>
                  {checked[doc] && (
                    <span className="ml-auto text-green-700 font-extrabold animate-check-pop flex items-center gap-1">
                      <span>✓</span> Ready
                    </span>
                  )}
                </label>
              </li>
            ))}
          </ul>

          {/* Progress summary */}
          <div className="mt-5 rounded-2xl border border-[var(--border)] bg-white p-4 text-lg font-semibold">
            {selected.documents.filter((d) => checked[d]).length} /{" "}
            {selected.documents.length} documents ready
            {selected.documents.filter((d) => checked[d]).length ===
              selected.documents.length && (
              <span className="ml-2 text-green-600 font-bold animate-fade-in">
                🎉 All set! You&apos;re ready to apply.
              </span>
            )}
          </div>

          {/* Action buttons */}
          <div className="mt-5 flex flex-wrap gap-3">
            <button
              onClick={downloadPdf}
              className="btn-tactile w-full sm:w-auto rounded-2xl bg-[var(--primary)] px-6 py-3.5 text-lg font-bold text-white shadow-sm hover:bg-[var(--primary-hover)] cursor-pointer"
            >
              📄 Download PDF Checklist
            </button>
            <button
              onClick={() => setSelectedId(null)}
              className="btn-tactile w-full sm:w-auto rounded-2xl border-2 border-[var(--border)] px-6 py-3.5 text-lg font-semibold hover:bg-gray-100 cursor-pointer"
            >
              Close
            </button>
          </div>
        </section>
      )}
    </div>
  );
}
